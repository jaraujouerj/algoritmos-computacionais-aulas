lista = [123, 1, 0, 24, 1, 14]
print('A lista:', lista)
lista.append(34)
lista.append(2)
print('Acrescenta 2 itens:', lista)
lista.extend([45, 12])
print('Estende com 2 itens:', lista)
lista.insert(1, 345)
print('Insere item na posição i:', lista)
lista.remove(24)
print('Remove item:', lista)
lista.pop()
print('Retira último item:', lista)
print('A lista possui ', lista.count(1),
      'itens de valor 1.')
outralista = sorted(lista)
print('Outra lista ordenada: ', outralista)
lista.sort()
print('Ordena a lista:', lista)
lista.reverse()
print('Inverte a lista:', lista)
print('O elemento 14 está na posição ', lista.index(14))
print('O mínimo é ', min(lista), ' e o máximo é ',
      max(lista))
